#!/usr/bin/env node
// Regenerates cards.js from cards.json, and cer-questions.js from
// cer-questions.json, so the app also works when index.html is opened straight
// from disk (file://), where fetch() of a .json file fails. Also rebuilds the
// single-file version, p3-science-flashcards.html.
//
// Usage: node build-cards.js

'use strict';

const fs = require('fs');
const path = require('path');

const standalonePath = 'p3-science-flashcards.html';
const CER_PARTS = ['C', 'E', 'R'];

function fail(message) {
  console.error('Error: ' + message);
  process.exit(1);
}

function readJson(name) {
  try {
    return JSON.parse(fs.readFileSync(path.join(__dirname, name), 'utf8'));
  } catch (err) {
    return fail('could not read ' + name + ' (' + err.message + ')');
  }
}

function isText(value) {
  return typeof value === 'string' && value.trim() !== '';
}

function writeDataScript(fileName, sourceName, globalName, data) {
  const output =
    '// Generated by build-cards.js from ' + sourceName + '. Do not edit this file by hand:\n' +
    '// edit ' + sourceName + ', then run `node build-cards.js`.\n' +
    'window.' + globalName + ' = ' + JSON.stringify(data, null, 2) + ';\n';
  fs.writeFileSync(path.join(__dirname, fileName), output, 'utf8');
}

// ---------- Flashcards ----------

const cards = readJson('cards.json');
if (!Array.isArray(cards) || cards.length === 0) {
  fail('cards.json must be a list [ ... ] with at least one card.');
}

const seenIds = new Set();
const topicNames = new Map();
cards.forEach((card, i) => {
  const where = 'card ' + (i + 1) + (card && card.id ? ' (id "' + card.id + '")' : '');
  if (!card || typeof card !== 'object') fail(where + ' is not an object.');
  ['id', 'topic', 'front', 'back'].forEach((field) => {
    if (!isText(card[field])) fail(where + ' is missing "' + field + '".');
  });
  if (!Number.isInteger(card.topicOrder) || card.topicOrder < 1) {
    fail(where + ' needs "topicOrder" to be a whole number like 1, 2, 3.');
  }
  if (seenIds.has(card.id)) fail(where + ' uses an id that is already taken.');
  seenIds.add(card.id);
  const name = topicNames.get(card.topicOrder);
  if (name !== undefined && name !== card.topic) {
    fail(where + ' has topicOrder ' + card.topicOrder + ' but topic "' + card.topic +
      '" (other cards with that topicOrder use "' + name + '").');
  }
  topicNames.set(card.topicOrder, card.topic);
});

// ---------- CER questions ----------

const cer = readJson('cer-questions.json');
if (!Array.isArray(cer)) fail('cer-questions.json must be a list [ ... ].');

const seenCerIds = new Set();
cer.forEach((q, i) => {
  const where = 'CER question ' + (i + 1) + (q && q.id ? ' (id "' + q.id + '")' : '');
  if (!q || typeof q !== 'object') fail(where + ' is not an object.');
  ['id', 'situation', 'question'].forEach((field) => {
    if (!isText(q[field])) fail(where + ' is missing "' + field + '".');
  });
  if (seenCerIds.has(q.id)) fail(where + ' uses an id that is already taken.');
  seenCerIds.add(q.id);
  if (!topicNames.has(q.topicOrder)) {
    fail(where + ' has topicOrder ' + q.topicOrder + ', but no flashcard topic has that number.');
  }
  if (!Array.isArray(q.statements) || q.statements.length < 3) {
    fail(where + ' needs at least 3 statements.');
  }
  q.statements.forEach((s, j) => {
    if (!s || !isText(s.text)) fail(where + ', statement ' + (j + 1) + ' is missing "text".');
    if (CER_PARTS.indexOf(s.part) === -1) {
      fail(where + ', statement ' + (j + 1) + ' needs "part" to be "C", "E" or "R".');
    }
  });
  CER_PARTS.forEach((part) => {
    if (!q.statements.some((s) => s.part === part)) {
      fail(where + ' needs at least one statement with "part": "' + part + '".');
    }
  });
});

// ---------- Write files ----------

writeDataScript('cards.js', 'cards.json', 'CARDS', cards);
writeDataScript('cer-questions.js', 'cer-questions.json', 'CER_QUESTIONS', cer);

// One self-contained HTML file (styles, data and app all inside), which is
// easy to email, upload or share as a single file.
const read = (name) => fs.readFileSync(path.join(__dirname, name), 'utf8');
const inlineJson = (data) => JSON.stringify(data, null, 2).replace(/<\//g, '<\\/');
const standalone = read('index.html')
  .replace('<link rel="stylesheet" href="styles.css">', () => '<style>\n' + read('styles.css') + '</style>')
  .replace('<script src="cards.js"></script>', () =>
    '<script>\nwindow.CARDS_INLINE = true;\nwindow.CARDS = ' + inlineJson(cards) + ';\n' +
    'window.CER_QUESTIONS = ' + inlineJson(cer) + ';\n</script>')
  .replace('<script src="cer-questions.js"></script>\n', '')
  .replace('<script src="app.js"></script>', () => '<script>\n' + read('app.js') + '</script>');
fs.writeFileSync(path.join(__dirname, standalonePath), standalone, 'utf8');

console.log('Wrote cards.js, cer-questions.js and ' + standalonePath + '.');
console.log(cards.length + ' flashcards:');
[...topicNames.keys()].sort((a, b) => a - b).forEach((order) => {
  const count = cards.filter((c) => c.topicOrder === order).length;
  console.log('  Topic ' + order + ': ' + topicNames.get(order) + ' (' + count + ')');
});
console.log(cer.length + ' CER questions.');
